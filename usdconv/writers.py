"""Output writers: OpenUSD (ASCII .usda, payloaded tiles) and binary glTF (.glb)."""
import json
import re
import struct

import numpy as np

from .engine import BuildResult, Mesh
from .spec import LayerSpec


def ident(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return ("_" + s) if not re.match(r"[A-Za-z_]", s or "_") else (s or "_")


def tile_id(t) -> str:
    f = lambda n: ("m" if n < 0 else "p") + str(abs(n))  # noqa: E731
    return f"t_{f(t[0])}_{f(t[1])}"


def hex_rgb(c: str):
    return tuple(int(c[i:i + 2], 16) / 255 for i in (1, 3, 5))


def _mesh_usda(m: Mesh, color: str, indent: str = "    ") -> str:
    pts = ", ".join(f"({x:.3f}, {y:.3f}, {z:.3f})" for x, y, z in m.verts)
    idx = ", ".join(map(str, m.faces.reshape(-1).tolist()))
    counts = ", ".join(["3"] * len(m.faces))
    r, g, b = hex_rgb(color)
    return f'''{indent}def Mesh "mesh" {{
{indent}    int[] faceVertexCounts = [{counts}]
{indent}    int[] faceVertexIndices = [{idx}]
{indent}    point3f[] points = [{pts}]
{indent}    uniform token subdivisionScheme = "none"
{indent}    bool doubleSided = true
{indent}    color3f[] primvars:displayColor = [({r:.4f}, {g:.4f}, {b:.4f})] (
{indent}        interpolation = "constant"
{indent}    )
{indent}}}
'''


def write_usd(res: BuildResult, name: str) -> dict[str, bytes]:
    """Returns {relative_path: bytes}: scene.usda + tiles/*.usda (referenced as payloads)."""
    files: dict[str, bytes] = {}
    body = []
    for l in res.layers:
        lid = ident(l.spec.name)
        body.append(f'        def Xform "{lid}"\n        {{\n')
        for t, m in sorted(l.tiles.items()):
            tid = tile_id(t)
            path = f"tiles/{lid}__{tid}.usda"
            files[path] = (
                '#usda 1.0\n(\n    defaultPrim = "Tile"\n    metersPerUnit = 1\n    upAxis = "Z"\n)\n\n'
                'def Xform "Tile"\n{\n' + _mesh_usda(m, l.spec.color) + "}\n").encode()
            body.append(f'            def Xform "{tid}" (\n                payload = @./{path}@\n            )\n            {{\n            }}\n')
        body.append("        }\n")
    safe_name = name.replace('"', "'")
    scene = (
        '#usda 1.0\n(\n    defaultPrim = "World"\n    metersPerUnit = 1\n    upAxis = "Z"\n'
        f'    doc = "Generated by usd-converter: {safe_name}"\n'
        '    customLayerData = {\n'
        f'        string targetCRS = "{res.target_crs}"\n'
        f'        double2 anchor = ({res.anchor[0]:.3f}, {res.anchor[1]:.3f})\n'
        f'        double tileSizeM = {res.tile_size_m}\n'
        '    }\n)\n\n'
        'def Xform "World"\n{\n' + "".join(body) + "}\n")
    files["scene.usda"] = scene.encode()
    return files


def write_glb(layers: list[tuple[LayerSpec, Mesh]]) -> bytes:
    """Single-buffer GLB; local Z-up metres converted to glTF Y-up (x, z, -y)."""
    bin_chunks, views, accessors, meshes, materials, nodes = [], [], [], [], [], []

    def add(data: bytes, target: int) -> int:
        off = sum(len(c) for c in bin_chunks)
        pad = (-len(data)) % 4
        bin_chunks.append(data + b"\0" * pad)
        views.append({"buffer": 0, "byteOffset": off, "byteLength": len(data), "target": target})
        return len(views) - 1

    for spec, m in layers:
        v = m.verts.astype(np.float32)
        pos = np.column_stack([v[:, 0], v[:, 2], -v[:, 1]]).astype(np.float32)
        idx = m.faces.astype(np.uint32).reshape(-1)
        pv = add(pos.tobytes(), 34962)
        iv = add(idx.tobytes(), 34963)
        accessors.append({"bufferView": pv, "componentType": 5126, "count": len(pos), "type": "VEC3",
                          "min": pos.min(axis=0).tolist(), "max": pos.max(axis=0).tolist()})
        accessors.append({"bufferView": iv, "componentType": 5125, "count": len(idx), "type": "SCALAR"})
        r, g, b = hex_rgb(spec.color)
        materials.append({"name": spec.name, "doubleSided": True,
                          "pbrMetallicRoughness": {"baseColorFactor": [r, g, b, 1], "metallicFactor": 0.0, "roughnessFactor": 0.9}})
        meshes.append({"name": spec.name, "primitives": [{"attributes": {"POSITION": len(accessors) - 2},
                                                             "indices": len(accessors) - 1, "material": len(materials) - 1}]})
        nodes.append({"name": spec.name, "mesh": len(meshes) - 1})
    binary = b"".join(bin_chunks)
    gltf = {"asset": {"version": "2.0", "generator": "usd-converter"}, "scene": 0,
            "scenes": [{"nodes": list(range(len(nodes)))}], "nodes": nodes, "meshes": meshes,
            "materials": materials, "accessors": accessors, "bufferViews": views,
            "buffers": [{"byteLength": len(binary)}]}
    js = json.dumps(gltf, separators=(",", ":")).encode()
    js += b" " * ((-len(js)) % 4)
    total = 12 + 8 + len(js) + 8 + len(binary)
    return (struct.pack("<III", 0x46546C67, 2, total) + struct.pack("<II", len(js), 0x4E4F534A) + js
            + struct.pack("<II", len(binary), 0x004E4942) + binary)
